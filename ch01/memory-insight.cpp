/**
 * =====================================================
 *   指针与内存 — 调试器观察例程
 * =====================================================
 *
 * 使用方法:
 *   1. 以 Debug 模式编译并运行本程序
 *   2. 在标记了 【断点】 的行上设置断点
 *   3. 启动调试，逐步观察 Variables / Memory 窗口
 *
 * 观察技巧:
 *   - 在 Variables 窗口中查看每个变量的"值"
 *   - 对于指针变量，注意它的值 = 它所指向变量的地址
 *   - 在 Memory 窗口中输入变量地址，查看内存中的字节
 *   - 十六进制魔术值便于在内存中快速定位:
 *       0xAAAA  / 0xBBBB  → 普通整数
 *       0x12345678        → 指针目标
 *       0xCAFEBABE        → 通过指针写入的新值
 *
 * slides 引用方式:
 *   <<< @/snippets/ch01/memory-insight.cpp#vars
 *   <<< @/snippets/ch01/memory-insight.cpp#ptr
 * =====================================================
 */

#include <cstdio>
#include <cstring>

int main() {

    /* ==========================================================
     * 第1步: 普通变量 — 每个变量都有地址和值
     * ==========================================================
     *
     * 内存布局示意 (地址仅为示例，实际值由系统分配):
     *
     *   地址(假设)     变量名    内存中的值
     *   ──────────    ──────    ──────────
     *   0x7fff...00   a         44 33 22 11  (小端: 0x11223344)
     *   0x7fff...04   b         88 77 66 55  (小端: 0x55667788)
     *
     * 【观察要点】
     *   在调试器中查看 &a 和 &b，注意:
     *   - 每个变量都占据内存中的一个位置
     *   - &a 和 &b 相差 4 字节 (因为 int 占 4 字节)
     */
// #region vars
    int a = 0x11223344;                          // 【断点】观察 a 的值和 &a
    int b = 0x55667788;                          // 【断点】观察 b 的值和 &b

    printf("===== 第1步: 普通变量 =====\n");
    printf("a = 0x%08X,  &a = %p\n", a, (void *)&a);
    printf("b = 0x%08X,  &b = %p\n", b, (void *)&b);
    long addr_diff = (long)((char *)&b - (char *)&a);
    if (addr_diff < 0) addr_diff = -addr_diff;
    printf("地址差: |&b - &a| = %ld 字节 (编译器分配顺序可能不同)\n\n", addr_diff);
// #endregion vars


    /* ==========================================================
     * 第2步: 指针 — 指针的值就是另一个变量的地址
     * ==========================================================
     *
     *   变量       值
     *   ────       ──────────────────────
     *   a          0x11223344
     *   p          &a 的值 (例如 0x7fff...00)  ← p 的值就是 a 的地址!
     *
     *   *p 和 a 访问的是同一块内存
     *
     * 【核心概念】
     *   p 的值  ==  &a     (指针里存的是地址)
     *   *p      ==  a      (* 是"解引用"，沿地址找到值)
     */
// #region ptr
    int *p = &a;                                   // 【断点】比较 p 的值和 &a

    printf("===== 第2步: 指针 =====\n");
    printf("p  = %p\n", (void *)p);
    printf("&a = %p\n", (void *)&a);
    printf("p == &a ? %s\n", (p == &a) ? "YES ✓" : "NO");
    printf("*p = 0x%08X  (和 a 相同!)\n\n", *p);
// #endregion ptr


    /* ==========================================================
     * 第3步: 通过指针修改值 — *p 和 a 是同一块内存
     * ==========================================================
     *
     *   执行 *p = 0xCAFEBABE 前后:
     *
     *   地址          修改前          修改后
     *   ──────────    ──────────      ──────────
     *   &a (即 p)     44 33 22 11     BE BA FE CA  (小端)
     *
     * 【观察要点】
     *   在 Memory 窗口中监视 &a 处的 4 个字节，
     *   执行 *p = ... 后，内存中的字节发生了变化，
     *   虽然我们没有直接写 a，但 a 的值变了!
     */
    *p = 0xCAFEBABE;                               // 【断点】观察 a 的值是否改变

    printf("===== 第3步: 通过指针修改值 =====\n");
    printf("执行 *p = 0xCAFEBABE 后:\n");
    printf("a  = 0x%08X  (被指针 p 修改了!)\n\n", a);


    /* ==========================================================
     * 第4步: 数组与指针 — 数组名就是首元素的地址
     * ==========================================================
     *
     *   数组 arr 在内存中连续存放 5 个 int:
     *
     *   地址(示例)     arr[0]   arr[1]   arr[2]   arr[3]   arr[4]
     *   ──────────    ──────   ──────   ──────   ──────   ──────
     *   0x7fff...10   0A00..   1400..   1E00..   2800..   3200..
     *                  ↑
     *                  arr / ptr 指向这里
     *
     * 【观察要点】
     *   - arr 和 &arr[0] 的值相同
     *   - ptr + 1 比 ptr 大 4 (不是 1! 因为 int 占 4 字节)
     *   - 相邻元素地址之差 = sizeof(int) = 4
     */
    int arr[5] = {10, 20, 30, 40, 50};             // 【断点】观察 arr 在内存中的布局
    int *ptr = arr;                                // 【断点】比较 ptr 和 arr 的值

    printf("===== 第4步: 数组与指针 =====\n");
    printf("arr    = %p,  &arr[0] = %p  (相同!)\n", (void *)arr, (void *)&arr[0]);
    printf("ptr    = %p,  *ptr = %d\n", (void *)ptr, *ptr);

    ptr = ptr + 1;                                 // 【断点】观察 ptr 增加了多少
    printf("ptr+1  = %p,  *ptr = %d  (指向 arr[1])\n", (void *)ptr, *ptr);
    printf("相邻 int 元素地址差: %ld 字节\n\n",
           (long)((char *)&arr[1] - (char *)&arr[0]));


    /* ==========================================================
     * 第5步: 字符数组与指针 — 指针可以逐字节遍历字符串
     * ==========================================================
     *
     *   字符数组 s 在内存中:
     *
     *   地址(示例)     s[0]   s[1]   s[2]   s[3]   s[4]   s[5]
     *   ──────────    ────   ────   ────   ────   ────   ────
     *   0x7fff...20    'a'    'p'    'p'    'l'    'e'   '\0'
     *                   ↑
     *                   s / sp 指向这里
     *
     * 【观察要点】
     *   - char 占 1 字节，所以 sp+1 比 sp 大 1
     *   - 通过 *sp = 'x' 可以修改数组中的字符
     *   - 在 Memory 窗口中可以看到对应字节从 'p'(0x70) 变为 'x'(0x78)
     */
    char s[] = "apple";                            // 【断点】观察 s 在内存中的 6 个字节
    char *sp = s;                                  // 【断点】比较 sp 和 s

    printf("===== 第5步: 字符数组与指针 =====\n");
    printf("s  = \"%s\",  sp = %p\n", s, (void *)sp);
    printf("*sp = '%c' (ASCII 0x%02X)\n", *sp, (unsigned char)*sp);

    sp++;                                          // 【断点】sp 增加了 1 字节
    printf("sp++ 后: *sp = '%c' (现在指向 s[1])\n", *sp);

    *sp = 'x';                                     // 【断点】观察 s 的变化
    printf("*sp = 'x' 后: s = \"%s\"\n", s);
    printf("(在 Memory 窗口中可以看到 'p'→'x', 即 0x70→0x78)\n\n");


    /* ==========================================================
     * 第6步: 结构体与指针 — 指针可以访问结构体成员
     * ==========================================================
     *
     *   结构体 stu 在内存中 (各成员连续存放):
     *
     *   偏移     成员        值
     *   ────    ────────    ──────────
     *   +0      id          0x00000007
     *   +4      name[0..7]  'L','i','n','\0',...
     *   +12     score       0x0000005A (90)
     *
     * 【观察要点】
     *   - rp 的值 = &stu
     *   - (*rp).id  等价于  rp->id
     *   - 在 Memory 窗口中从 rp 地址开始，可以依次看到各成员
     *   - 注意成员之间的内存对齐 (padding)
     */
    struct student {
        int id;              // 偏移 +0,  4 字节
        char name[8];        // 偏移 +4,  8 字节
        int score;           // 偏移 +12, 4 字节
    };

    struct student stu = {7, "Lin", 90};             // 【断点】观察 stu 的内存布局
    struct student *rp = &stu;                       // 【断点】比较 rp 和 &stu

    printf("===== 第6步: 结构体与指针 =====\n");
    printf("rp   = %p,  &stu = %p  (相同!)\n", (void *)rp, (void *)&stu);
    printf("(*rp).id    = %d\n",    (*rp).id);
    printf("rp->name    = \"%s\"\n", rp->name);
    printf("rp->score   = %d\n",    rp->score);

    rp->score = 100;                                 // 【断点】观察 stu.score 的变化
    printf("\n通过 rp->score = 100 修改后:\n");
    printf("stu.score = %d\n", stu.score);


    /* ==========================================================
     * 总结
     * ========================================================== */
    printf("\n===== 总结 =====\n");
    printf("1. 每个变量都有地址 (&x), 指针里存的就是地址\n");
    printf("2. *p 和 p 指向的变量是同一块内存\n");
    printf("3. 通过 *p 修改值 = 直接修改那块内存\n");
    printf("4. 数组名 = 首元素地址, ptr+1 跳过整个元素大小\n");
    printf("5. 结构体指针用 -> 访问成员\n");

    return 0;
}
